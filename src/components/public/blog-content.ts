/**
 * Every image of a post, cover first.
 * @param post Blog post.
 * @returns Cover, section images, then attached images, without repeats.
 */
export function allBlogImages(post: BlogPost): BlogImage[] {
  const images = [...(post.cover ? [post.cover] : []), ...post.sections.flatMap((s) => s.images ?? []), ...(post.assets?.images ?? [])];
  return images.filter((img, i) => images.findIndex((other) => other.src === img.src) === i);
}

export function getBlogBySlug(slug: string) {
  return blogPosts.find((p) => p.slug === slug) ?? null;
}
